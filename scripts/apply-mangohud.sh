#!/bin/sh
# Применить настройки MangoHud из prefs.json в конфиг ~/.config/MangoHud/MangoHud.conf
set -e

CONF="$HOME/.config/MangoHud/MangoHud.conf"
PREFS="$HOME/oberon/prefs.json"
mkdir -p "$(dirname "$CONF")"

if command -v python3 >/dev/null 2>&1; then
    python3 - "$PREFS" "$CONF" << 'PY'
import json
import sys

prefs_path, conf_path = sys.argv[1], sys.argv[2]
try:
    with open(prefs_path, encoding="utf-8") as f:
        d = json.load(f)
    if not isinstance(d, dict):
        d = {}
except Exception:
    d = {}

def b(key, default):
    return "true" if bool(d.get(key, default)) else "false"

enabled = bool(d.get("mangohudEnabled", False))
pos = str(d.get("mangohudPosition", "top-left") or "top-left").strip()
horizontal = bool(d.get("mangohudHorizontal", False))
try:
    fps_limit = int(d.get("mangohudFpsLimit", 0) or 0)
except Exception:
    fps_limit = 0
toggle_key = str(d.get("mangohudToggleKey", "Shift_R+F12") or "Shift_R+F12").strip()

lines = [
    "# MangoHud configuration — auto-generated by Oberon",
    "# Edit via Oberon Settings → Games",
    "",
    f"position={pos}",
    f"toggle_hud={toggle_key}",
    f"fps={b('mangohudFPS', True)}",
    f"cpu={b('mangohudCPU', True)}",
    f"gpu={b('mangohudGPU', True)}",
    f"ram={b('mangohudRAM', True)}",
    f"vram={b('mangohudVRAM', False)}",
    f"frametime={b('mangohudFrameTime', True)}",
    f"version={b('mangohudVersion', False)}",
    f"engine={b('mangohudEngine', False)}",
    f"io={b('mangohudIO', False)}",
    f"media={b('mangohudMedia', False)}",
    f"alpha={d.get('mangohudHudAlpha', 1.0)}",
]
if horizontal:
    lines.append("horizontal")
if fps_limit > 0:
    lines.append(f"fps_limit={fps_limit}")
if not enabled:
    lines.append("no_display=true")

with open(conf_path, "w", encoding="utf-8") as f:
    f.write("\n".join(lines) + "\n")
PY
else
    # Fallback на случай отсутствия python3
    get_bool() {
        key="$1"
        def="$2"
        if [ -f "$PREFS" ]; then
            val=$(sed -n 's/.*"'"$key"'"[[:space:]]*:[[:space:]]*\(true\|false\).*/\1/p' "$PREFS" | head -n 1)
            if [ -n "$val" ]; then
                printf '%s' "$val"
                return
            fi
        fi
        printf '%s' "$def"
    }
    get_str() {
        key="$1"
        def="$2"
        if [ -f "$PREFS" ]; then
            val=$(sed -n 's/.*"'"$key"'"[[:space:]]*:[[:space:]]*"\([^"]*\)".*/\1/p' "$PREFS" | head -n 1)
            if [ -n "$val" ]; then
                printf '%s' "$val"
                return
            fi
        fi
        printf '%s' "$def"
    }
    get_num() {
        key="$1"
        def="$2"
        if [ -f "$PREFS" ]; then
            val=$(sed -n 's/.*"'"$key"'"[[:space:]]*:[[:space:]]*\([0-9.]*\).*/\1/p' "$PREFS" | head -n 1)
            if [ -n "$val" ]; then
                printf '%s' "$val"
                return
            fi
        fi
        printf '%s' "$def"
    }

    enabled=$(get_bool mangohudEnabled false)
    pos=$(get_str mangohudPosition "top-left")
    horizontal=$(get_bool mangohudHorizontal false)
    fps_limit=$(get_num mangohudFpsLimit 0)
    toggle_key=$(get_str mangohudToggleKey "Shift_R+F12")
    alpha=$(get_num mangohudHudAlpha 1.0)

    {
        echo "# MangoHud configuration — auto-generated by Oberon"
        echo "# Edit via Oberon Settings → Games"
        echo ""
        echo "position=$pos"
        echo "toggle_hud=$toggle_key"
        echo "fps=$(get_bool mangohudFPS true)"
        echo "cpu=$(get_bool mangohudCPU true)"
        echo "gpu=$(get_bool mangohudGPU true)"
        echo "ram=$(get_bool mangohudRAM true)"
        echo "vram=$(get_bool mangohudVRAM false)"
        echo "frametime=$(get_bool mangohudFrameTime true)"
        echo "version=$(get_bool mangohudVersion false)"
        echo "engine=$(get_bool mangohudEngine false)"
        echo "io=$(get_bool mangohudIO false)"
        echo "media=$(get_bool mangohudMedia false)"
        echo "alpha=$alpha"
        [ "$horizontal" = "true" ] && echo "horizontal" || true
        if [ -n "$fps_limit" ] && [ "${fps_limit%.*}" -gt 0 ] 2>/dev/null; then
            echo "fps_limit=${fps_limit%.*}"
        fi
        [ "$enabled" = "false" ] && echo "no_display=true" || true
    } > "$CONF"
fi

echo "MangoHud config applied: $CONF"
